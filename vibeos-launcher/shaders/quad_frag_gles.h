/* GLSL ES 3.00 from quad.frag (tools/shaders.sh) */
#pragma once
static const char quad_frag_gles[] =
  "#version 300 es\n"
  "precision highp float;\n"
  "precision highp int;\n"
  "precision highp sampler2D;\n"
  "// Shared by every stage: the push constants (gfx-backend.h's GfxPush). OpenGL ES has no push constants: a uniform\n"
  "// struct of the same members stands in for them there, and the macros below cover what else the two dialects spell\n"
  "// differently (glslang defines VULKAN when it compiles for Vulkan; the OpenGL ES driver does not).\n"
  "#ifdef VULKAN\n"
  "layout(push_constant) uniform Push {\n"
  "  vec2 vp;      // the pass's size in pixels\n"
  "  vec2 pad;\n"
  "  vec4 p0;      // effect parameters\n"
  "  vec4 p1;\n"
  "} pc;\n"
  "#define LOC(n) layout(location = n)\n"
  "#define TEX_BINDING layout(set = 0, binding = 0)\n"
  "#define VERTEX_INDEX gl_VertexIndex\n"
  "#else\n"
  "struct Push {\n"
  "  vec2 vp;      // the pass's size in pixels\n"
  "  vec2 pad;     // x: 1 when the pass draws to the window, whose rows OpenGL ES counts from the bottom\n"
  "  vec4 p0;      // effect parameters\n"
  "  vec4 p1;\n"
  "};\n"
  "uniform Push pc;\n"
  "#define LOC(n)\n"
  "#define TEX_BINDING\n"
  "#define VERTEX_INDEX gl_VertexID\n"
  "#endif\n"
  "// Coverage of the rounded rect and the clip at this fragment\n"
  "float rrect_coverage(vec2 local, vec4 shape)\n"
  "{\n"
  "  vec2 q = abs(local) - shape.xy + shape.z;\n"
  "  float d = length(max(q, 0.0)) + min(max(q.x, q.y), 0.0) - shape.z;\n"
  "  float w = max(fwidth(d), 1e-4);\n"
  "  return clamp(0.5 - d / w, 0.0, 1.0);\n"
  "}\n"
  "\n"
  "float clip_coverage(vec4 clip)\n"
  "{\n"
  "  if (clip.z <= clip.x)\n"
  "    return 1.0;\n"
  "  vec2 fc = gl_FragCoord.xy;\n"
  "#ifndef VULKAN\n"
  "  if (pc.pad.x != 0.0)          // the window: its rows counted from the top, as everywhere else\n"
  "    fc.y = pc.vp.y - fc.y;\n"
  "#endif\n"
  "  vec2 a = clamp(fc - clip.xy + 0.5, 0.0, 1.0);\n"
  "  vec2 b = clamp(clip.zw - fc + 0.5, 0.0, 1.0);\n"
  "  return a.x * a.y * b.x * b.y;\n"
  "}\n"
  "\n"
  "TEX_BINDING uniform sampler2D tex;\n"
  "\n"
  "LOC(0) in vec2 v_uv;\n"
  "LOC(1) in vec2 v_local;\n"
  "LOC(2) flat in vec4 v_color;\n"
  "LOC(3) flat in vec4 v_shape;\n"
  "LOC(4) flat in vec4 v_clip;\n"
  "LOC(5) flat in vec4 v_extra;\n"
  "\n"
  "layout(location = 0) out vec4 o;\n"
  "\n"
  "void main()\n"
  "{\n"
  "  float cov = clip_coverage(v_clip);\n"
  "  vec4 c;\n"
  "  if (v_shape.w == 2.0) {                       // glyph mask\n"
  "    c = v_color * texture(tex, v_uv).r;\n"
  "  } else if (v_shape.w == 3.0) {                // a colour, each corner its own radius (tl tr br bl)\n"
  "    float r = v_local.x < 0.0 ? (v_local.y < 0.0 ? v_extra.x : v_extra.w) : (v_local.y < 0.0 ? v_extra.y : v_extra.z);\n"
  "    cov *= rrect_coverage(v_local, vec4(v_shape.xy, r, 0.0));\n"
  "    c = v_color;\n"
  "  } else if (v_shape.w == 4.0) {                // an outline v_extra.x wide, inside the rect\n"
  "    float w = v_extra.x;\n"
  "    cov *= rrect_coverage(v_local, v_shape) -\n"
  "           rrect_coverage(v_local, vec4(v_shape.xy - w, max(v_shape.z - w, 0.0), 0.0));\n"
  "    c = v_color;\n"
  "  } else {\n"
  "    cov *= rrect_coverage(v_local, v_shape);\n"
  "    c = v_shape.w == 1.0 ? v_color : v_color * texture(tex, v_uv);\n"
  "  }\n"
  "  o = c * cov;\n"
  "}\n"
  ;
