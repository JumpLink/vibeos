/* GLSL ES 3.00 from quad.vert (tools/shaders.sh) */
#pragma once
static const char quad_vert_gles[] =
  "#version 300 es\n"
  "precision highp float;\n"
  "precision highp int;\n"
  "precision highp sampler2D;\n"
  "// Shared by every stage: the push constants (gfx-backend.h's GfxPush). OpenGL ES has no push constants: a uniform\n"
  "// struct of the same members stands in for them there, and the macros below cover what else the two dialects spell\n"
  "// differently (glslang defines VULKAN when it compiles for Vulkan; the OpenGL ES driver does not).\n"
  "#ifdef VULKAN\n"
  "layout(push_constant) uniform Push {\n"
  "  vec2 vp;      // the pass's size in pixels\n"
  "  vec2 pad;\n"
  "  vec4 p0;      // effect parameters\n"
  "  vec4 p1;\n"
  "} pc;\n"
  "#define LOC(n) layout(location = n)\n"
  "#define TEX_BINDING layout(set = 0, binding = 0)\n"
  "#define VERTEX_INDEX gl_VertexIndex\n"
  "#else\n"
  "struct Push {\n"
  "  vec2 vp;      // the pass's size in pixels\n"
  "  vec2 pad;     // x: 1 when the pass draws to the window, whose rows OpenGL ES counts from the bottom\n"
  "  vec4 p0;      // effect parameters\n"
  "  vec4 p1;\n"
  "};\n"
  "uniform Push pc;\n"
  "#define LOC(n)\n"
  "#define TEX_BINDING\n"
  "#define VERTEX_INDEX gl_VertexID\n"
  "#endif\n"
  "\n"
  "// One GfxInst per instance\n"
  "layout(location = 0) in vec4 i_rect;    // x y w h, the rect in its own space\n"
  "layout(location = 1) in vec4 i_uv;      // u0 v0 u1 v1\n"
  "layout(location = 2) in vec4 i_color;   // premultiplied\n"
  "layout(location = 3) in vec4 i_m;       // screen = [m0 m1; m2 m3] p + t\n"
  "layout(location = 4) in vec4 i_misc;    // tx ty radius mode\n"
  "layout(location = 5) in vec4 i_clip;    // screen x0 y0 x1 y1\n"
  "\n"
  "LOC(0) out vec2 v_uv;\n"
  "LOC(1) out vec2 v_local;          // from the rect's centre, in its own units\n"
  "LOC(2) flat out vec4 v_color;\n"
  "LOC(3) flat out vec4 v_shape;     // half w, half h, radius, mode\n"
  "LOC(4) flat out vec4 v_clip;\n"
  "LOC(5) flat out vec4 v_extra;     // the corners' radii (mode 3), the ring's width (mode 4)\n"
  "\n"
  "const vec2 corners[6] = vec2[](vec2(0, 0), vec2(1, 0), vec2(0, 1), vec2(0, 1), vec2(1, 0), vec2(1, 1));\n"
  "\n"
  "void main()\n"
  "{\n"
  "  vec2 c = corners[VERTEX_INDEX];\n"
  "  float mode = i_misc.w;\n"
  "\n"
  "  vec2 f, p;\n"
  "  if (mode == 5.0) {\n"
  "    // A piece of a picture: i_rect holds its edges, x0 y0 x1 y1, and each corner takes them as they are, not worked\n"
  "    // out from a size, so a piece sharing an edge with it puts that edge at the very same place\n"
  "    f = c;\n"
  "    p = vec2(c.x == 0.0 ? i_rect.x : i_rect.z, c.y == 0.0 ? i_rect.y : i_rect.w);\n"
  "  } else {\n"
  "    // Grow the quad by a pixel on every side so the edge can be antialiased; glyph masks are pixel-aligned and come\n"
  "    // from an atlas whose neighbours must not bleed in, so they keep their exact size\n"
  "    vec2 grow = vec2(0.0);\n"
  "    if (mode != 2.0) {\n"
  "      float sx = length(vec2(i_m.x, i_m.z));\n"
  "      float sy = length(vec2(i_m.y, i_m.w));\n"
  "      grow = vec2(1.0 / max(sx, 1e-4), 1.0 / max(sy, 1e-4));\n"
  "    }\n"
  "    f = mix(-grow / i_rect.zw, 1.0 + grow / i_rect.zw, c);   // rect-relative, may run past 0..1\n"
  "    p = i_rect.xy + f * i_rect.zw;\n"
  "  }\n"
  "\n"
  "  vec2 s = vec2(i_m.x * p.x + i_m.y * p.y, i_m.z * p.x + i_m.w * p.y) + i_misc.xy;\n"
  "  gl_Position = vec4(s / pc.vp * 2.0 - 1.0, 0.0, 1.0);\n"
  "#ifndef VULKAN\n"
  "  if (pc.pad.x != 0.0)          // the window, whose rows OpenGL ES counts from the bottom: drawn upside down\n"
  "    gl_Position.y = -gl_Position.y;\n"
  "#endif\n"
  "\n"
  "  v_uv = mode == 5.0 ? vec2(c.x == 0.0 ? i_uv.x : i_uv.z, c.y == 0.0 ? i_uv.y : i_uv.w) : mix(i_uv.xy, i_uv.zw, f);\n"
  "  v_local = (f - 0.5) * i_rect.zw;\n"
  "  v_color = i_color;\n"
  "  v_shape = vec4(i_rect.zw * 0.5, i_misc.z, mode);\n"
  "  v_clip = i_clip;\n"
  "  v_extra = i_uv;\n"
  "}\n"
  ;
