#!/usr/bin/env python3
# cities.py - DeskClock's world-clock cities (res/values/cities.xml) and its home time zones (the timezone_values
# and timezone_labels arrays of res/values/strings.xml) as C tables, for src/cities-data.h.
#
#   python3 tools/cities.py DESKCLOCK/res/values/cities.xml DESKCLOCK/res/values/strings.xml > src/cities-data.h
#
# Each city string reads "INDEX=NAME|ZONE": the section letter the picker files it under, the English name, and its
# IANA time zone. The table keeps the city_ids array's order and ids (C1 ... C348; some numbers are unused), which
# is what the selected cities are stored as. The names are marked for translation (NC_, the contexts "city" and "time
# zone"): the app shows them in the user's language, and DeskClock's own translations fill the translation files
# (tools/i18n/android-import.py). Python 3 stdlib only.
import sys
import xml.etree.ElementTree as ET


def text(el):
    """the string resource's text, xliff:g parts and all, with Android's escapes undone"""
    s = ''.join(el.itertext()).strip()
    if len(s) >= 2 and s[0] == s[-1] == '"':
        s = s[1:-1]
    return s.replace("\\'", "'").replace('\\"', '"')


root = ET.parse(sys.argv[1]).getroot()
strings = {el.get('name'): text(el) for el in root.iter('string')}
ids = [item.text.strip().split('/', 1)[1] for item in root.find("array[@name='city_ids']")]

print('/* Generated by tools/cities.py from LineageOS DeskClock res/values/cities.xml (Apache 2.0): every world-clock')
print(' * city, in city_ids order: { id, index, name, zone }; the names marked for translation. Do not edit; run the')
print(' * script again. */')
print('static const CityData city_data[] = {')
for cid in ids:
    entry, zone = strings[cid].split('|')
    index, name = entry.split('=', 1)
    name = name.split(':', 1)[0]     # a phonetic part, "NAME:PHONETIC", is for sorting in some languages
    c = lambda s: s.replace('\\', '\\\\').replace('"', '\\"')
    print(f'  {{ "{cid}", "{c(index)}", NC_("city", "{c(name)}"), "{zone}" }},')
print('};')

# The "Home time zone" setting's choices: 85 zones, each with an English place name;
# the settings page puts the offset in front, "(GMT+1:00) Amsterdam, Berlin", and sorts them by it.
res = ET.parse(sys.argv[2]).getroot()
array = lambda name: [text(item) for item in res.find(f"string-array[@name='{name}']")]
zones, labels = array('timezone_values'), array('timezone_labels')
assert len(zones) == len(labels)
print()
print('/* the home time zone choices, in strings.xml order: { zone, name } */')
print('static const HomeZoneData home_zone_data[] = {')
for zone, label in zip(zones, labels):
    print(f'  {{ "{zone}", NC_("time zone", "{c(label)}") }},')
print('};')
