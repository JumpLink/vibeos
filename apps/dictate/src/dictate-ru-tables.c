gboolean
ru_in (const char *const *list, const char *word)
{
  if (!word)
    return FALSE;
  for (; *list; list++)
    if (g_str_equal (*list, word))
      return TRUE;
  return FALSE;
}

const char *
ru_lookup (const RuPair *pairs, const char *key)
{
  if (!key)
    return NULL;
  for (; pairs->key; pairs++)
    if (g_str_equal (pairs->key, key))
      return pairs->value;
  return NULL;
}

gboolean
ru_is_preposition (const char *word)
{
  return ru_lookup (PREPOSITIONS, word) != NULL;
}

const char *
ru_cases (const char *preposition, const char *table)
{
  const char *cases = NULL;

  if (table && preposition)
    cases = ru_lookup (ru_pairs (table), preposition);
  if (!cases && preposition)
    cases = ru_lookup (PREPOSITIONS, preposition);
  return cases ? cases : "N";
}

